import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createCoreOrderClient} from '../core-order-client.mjs';
const fixture=JSON.parse(process.env.CORE_ORDER_FIXTURE);
const client=createCoreOrderClient({issuer:'https://platform.example',privateKey:fixture.privateKey,restaurants:[{id:'restaurant-a',baseUrl:fixture.baseUrl}]});
const owner=randomUUID(),other=randomUUID();
const input={...fixture.input,mode:'pickup',paymentMethod:'card',paymentProvider:'stripe',expectedTotalMinor:3000};
const order=await client.create('restaurant-a',owner,input,randomUUID());
assert.equal(order.paymentStatus,'unpaid');
const before=await client.payment('restaurant-a',owner,order.number,'status');assert.equal(before.status,'unpaid');
await assert.rejects(client.payment('restaurant-a',other,order.number,'start','stripe'),{code:'invalid_order_access'});
const started=await client.payment('restaurant-a',owner,order.number,'start','stripe');
assert.equal(started.status,'pending','Create response must never be treated as proof of payment');assert.equal(started.mode,'test');
assert.match(started.url,/^https:\/\/checkout\.stripe\.com\//);
assert.deepEqual(await client.payment('restaurant-a',owner,order.number,'start','stripe'),started);
const refreshed=await client.payment('restaurant-a',owner,order.number,'refresh');assert.equal(refreshed.status,'paid');
assert.equal((await client.status('restaurant-a',owner,order.number)).paymentStatus,'paid');
const feed=await client.events('restaurant-a',owner,0,100);
assert.deepEqual(feed.events.map(event=>event.sequence),[1,2,3]);
assert.deepEqual(feed.events.map(event=>event.order.paymentStatus),['unpaid','pending','paid']);
console.log('Verified signed payment initiation/repeat/owner isolation and independently fetched settlement; provider adapter mocked, no real money/network');
