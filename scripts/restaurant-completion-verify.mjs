// Read-only post-update verification; credentials and record contents are never printed.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const root = '/home/chatbot/wa/AstraCalls';
const snapshot = resolve(process.argv[2] || '');
if (process.cwd() !== root || !/^\/home\/chatbot\/wa\/AstraCalls\/backups\/completion-update\.[A-Za-z0-9]+$/.test(snapshot)) throw new Error('Expected private completion snapshot');
const before = JSON.parse(readFileSync(resolve(snapshot, 'before.json'), 'utf8'));
const run = args => execFileSync('docker', args, { encoding: 'utf8', maxBuffer: 1024 * 1024 }).trim();
const app = 'astracalls-main-astracalls-1', postgres = 'astracalls-main-postgres-1';
const sql = query => run(['exec', postgres, 'psql', '-U', 'astracalls', '-d', 'wacalls_main', '-At', '-c', query]);
const checks = [];
const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
check(run(['inspect', '--format', '{{.Id}}', postgres]) === before.postgres.id, 'PostgreSQL container preserved');
check(run(['inspect', '--format', '{{.State.StartedAt}}', postgres]) === before.postgres.startedAt, 'PostgreSQL not restarted');
check(Number(run(['inspect', '--format', '{{.RestartCount}}', postgres])) === before.postgres.restarts, 'PostgreSQL restart count unchanged');
check(sql("SELECT version || ':' || md5(document::text) FROM restaurant_catalog WHERE id=1") === before.catalog, 'Existing catalog unchanged');
check(sql('SELECT (SELECT count(*) FROM restaurant_orders),(SELECT count(*) FROM sessions),(SELECT count(*) FROM restaurant_couriers)') === before.counts, 'Existing order/session/courier counts unchanged');
check(sql("SELECT md5(COALESCE(jsonb_agg(to_jsonb(s) ORDER BY id)::text,'[]')) FROM sessions s") === before.sessionFingerprint, 'WhatsApp and translation session configuration preserved');
check(sql("SELECT md5(COALESCE(jsonb_agg(to_jsonb(p) ORDER BY provider)::text,'[]')) FROM restaurant_payment_configs p") === before.gatewayFingerprint, 'Gateway configuration preserved');
const currentEnv = readFileSync(resolve(root, '.env'), 'utf8');
const fingerprint = value => createHash('sha256').update(value.split(/\r?\n/).filter(line => !/^ASTRACALLS_(?:IMAGE|VERSION)=/.test(line)).join('\n')).digest('hex');
check(fingerprint(currentEnv) === fingerprint(readFileSync(resolve(snapshot, 'env.before'), 'utf8')), 'Environment unchanged except development image/version');
const rawKey = currentEnv.match(/^WACALLS_API_KEY=(.*)$/m)?.[1]?.trim();
const key = rawKey?.replace(/^(['"])(.*)\1$/, '$2');
if (!key) throw new Error('Administrator credential unavailable');
const origin = 'https://almujeeb.info';
const get = (path, admin = false) => fetch(origin + path, { headers: admin ? { 'X-API-Key': key } : {}, redirect: 'error', signal: AbortSignal.timeout(10000) });
check((await get('/healthz')).status === 200, 'HTTPS health check passed');
check((await get('/')).status === 200 && (await get('/admin')).status === 200, 'Customer and administrator pages available');
check([401, 403].includes((await get('/api/restaurant/archive/policy')).status), 'New administrative routes reject anonymous access');
const policyResponse = await get('/api/restaurant/archive/policy', true);
check(policyResponse.ok, 'Authenticated archive settings available');
const policy = await policyResponse.json();
check(policy.enabled === false && policy.retentionEnabled === false && policy.aiEnabled === false, 'Archive capture, deletion and AI remain disabled');
check((await get('/api/restaurant/stock', true)).ok && (await get('/api/restaurant/brand', true)).ok, 'New stock and appearance endpoints available');
const payments = await (await get('/api/restaurant/payments', true)).json();
check(payments.providers?.length === 7 && payments.providers.every(value => !value.enabled), 'All seven payment providers remain disabled');
check([401, 403].includes((await get('/recordings/completion-unauthenticated-check.mp3')).status), 'Legacy recording route requires authentication');
console.log(JSON.stringify({ checks, count: checks.length, image: run(['inspect', '--format', '{{.Config.Image}}', app]) }, null, 2));
